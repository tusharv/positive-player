import { acceptsProgram } from './program-policy.mjs'
import { createHash } from 'node:crypto'
import { mkdirSync, writeFileSync, renameSync } from 'node:fs'

// Shared by the API refresh script and local catalog migrations. No API calls.
export function writeProgramBundles(channels, catalogs, directory) {
  const rows = channels.map((channel) => {
    const items = catalogs[channel.name]
    if (!items?.length) throw new Error(`Missing bundle: ${channel.name}`)
    if (items.some((item) => !acceptsProgram(channel.name, item)))
      throw new Error(`Content policy violation: ${channel.name} requires video songs`)
    const json = JSON.stringify(items, null, 2) + '\n'
    return {
      name: channel.name,
      file: String(channel.number).padStart(3, '0'),
      version: createHash('sha256').update(json).digest('hex').slice(0, 16),
      json,
    }
  })
  mkdirSync(new URL('programs/', directory), { recursive: true })
  for (const row of rows) {
    const target = new URL(`programs/${row.file}.json`, directory)
    writeFileSync(new URL(`${target.href}.tmp`), row.json)
    renameSync(new URL(`${target.href}.tmp`), target)
  }
  // Vite serves JSON imports as JavaScript modules in development. A JSON
  // import attribute makes browsers reject those responses before playback.
  const manifest =
    `import type { CatalogItem } from '../lib/broadcastClock'\n\n` +
    `// Generated by npm run bundle:programs. Only the selected channel's import is invoked.\n` +
    `export const CURATED_PROGRAMS: Partial<Record<string, {\n` +
    `  version: string\n  load: () => Promise<CatalogItem[]>\n}>> = {\n` +
    rows
      .map(
        (row) =>
          `  ${JSON.stringify(row.name)}: {\n` +
          `    version: '${row.version}',\n` +
          `    load: () => import('./programs/${row.file}.json').then(m => m.default),\n` +
          `  },`,
      )
      .join('\n') +
    '\n}\n'
  const target = new URL('curatedPrograms.ts', directory)
  writeFileSync(new URL(`${target.href}.tmp`), manifest)
  renameSync(new URL(`${target.href}.tmp`), target)
}
